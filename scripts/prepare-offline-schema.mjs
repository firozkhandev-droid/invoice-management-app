import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "prisma", "schema.prisma");
const targetPath = path.join(root, "prisma", "schema.offline.prisma");

const source = await readFile(sourcePath, "utf8");

const offlineSchema = source
  .replace(
    /datasource db \{\s+provider = "mysql"\s+url\s+= env\("DATABASE_URL"\)\s+\}/,
    'datasource db {\n  provider = "sqlite"\n  url      = env("DATABASE_URL")\n}'
  )
  .replace(/\s+binaryTargets = \[[^\]]+\]/, "")
  .replace(/\s+@db\.[A-Za-z]+(?:\([^)]*\))?/g, "");

await writeFile(
  targetPath,
  [
    "// This file is generated by scripts/prepare-offline-schema.mjs.",
    "// Edit prisma/schema.prisma, then run npm run offline:schema.",
    offlineSchema.trim(),
    ""
  ].join("\n"),
  "utf8"
);

console.log(`Prepared offline Prisma schema at ${path.relative(root, targetPath)}.`);
